#!/bin/sh
# Build a minimal root filesystem in /rootfs from Debian packages: only the files the packages install,
# no shell, no apt, no dpkg. Usage: mkrootfs.sh <package>...   (run inside a Debian image)
#
# Why copy by `dpkg -L` instead of extracting .deb files: Debian is usr-merged (/lib -> usr/lib), and
# a .deb extracted over a different layout puts libraries where the loader does not look.
# Each package also leaves its control record in /var/lib/dpkg/status.d/ (the convention distroless
# uses), so Trivy and SBOM tools can list what the image contains and report CVEs against it.
set -eu

R=/rootfs
export DEBIAN_FRONTEND=noninteractive
apt-get update -qq
apt-get -y -qq upgrade                       # security fixes since the pinned base tag was cut
apt-get -y -qq install --no-install-recommends "$@"

mkdir -p "$R/usr/lib" "$R/usr/bin" "$R/etc" "$R/tmp" "$R/var/lib/dpkg/status.d" "$R/home/nonroot"
chmod 1777 "$R/tmp"
for link in lib lib64 bin sbin; do                       # keep the usr-merge symlinks as they are
  if [ -L "/$link" ]; then cp -a "/$link" "$R/$link"; fi
done

for pkg in "$@"; do
  dpkg -L "$pkg" | while IFS= read -r path; do
    if [ ! -f "$path" ] && [ ! -L "$path" ]; then continue; fi          # directories are created on demand
    case "$path" in
      /usr/share/doc/*/copyright) ;;                                    # keep licences
      /usr/share/doc/*|/usr/share/man/*|/usr/share/info/*|/usr/share/lintian/*|/usr/share/locale/*) continue ;;
    esac
    dir=$(readlink -f "$(dirname "$path")")
    mkdir -p "$R$dir"
    cp -a "$path" "$R$dir/"
  done
  dpkg-query -s "$pkg" > "$R/var/lib/dpkg/status.d/$pkg"
done

# glibc ships ~200 character-set converters (20 MB) that no server uses. Keep the Unicode ones and the
# two Western ones; the rest fail to load, which is the same as an image that never had them.
for gconv in "$R"/usr/lib/*/gconv; do
  [ -d "$gconv" ] || continue
  find "$gconv" -type f ! -name 'gconv-modules*' ! -name 'UTF-*' ! -name 'UNICODE.so' \
       ! -name 'ISO8859-1.so' ! -name 'ISO8859-15.so' ! -name 'CP1252.so' -delete
  rm -f "$gconv/gconv-modules.cache"
done
rm -f "$R/usr/sbin/update-ca-certificates"            # a script that needs a shell the image does not have

# CA bundle: generated by the ca-certificates postinst, so it is not in `dpkg -L`.
if [ -d /etc/ssl/certs ]; then
  mkdir -p "$R/etc/ssl"
  cp -a /etc/ssl/certs "$R/etc/ssl/"
fi

# Identity files. nonroot is 65532, the same uid distroless uses, so Kubernetes manifests carry over.
printf 'root:x:0:0:root:/root:/sbin/nologin\nnonroot:x:65532:65532:nonroot:/home/nonroot:/sbin/nologin\n' > "$R/etc/passwd"
printf 'root:x:0:\nnonroot:x:65532:\n' > "$R/etc/group"
printf 'hosts: files dns\n' > "$R/etc/nsswitch.conf"
chown -R 65532:65532 "$R/home/nonroot"
